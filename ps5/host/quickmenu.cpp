void osdDraw(float W, float H)
{
   const float u = H / 1080.0f;
   ImDrawList *dl = ImGui::GetForegroundDrawList();
   struct psgopher_live l = {};
   psgopher_live_read(&l);
   float hist[180];
   const int n = psgopher_live_history(hist, 180);
   const float x = 48 * u, y = 48 * u, w = 400 * u, h = 236 * u;
   dl->AddRectFilled(ImVec2(x, y), ImVec2(x + w, y + h), IM_COL32(7, 17, 21, 210), 14 * u);
   dl->AddRect(ImVec2(x, y), ImVec2(x + w, y + h), IM_COL32(140, 230, 220, 61), 14 * u, 1 * u);
   char t[128];
   const ImU32 speed_colour = l.speed >= 98 ? IM_COL32(0x4f, 0xf0, 0xe0, 255) : l.speed >= 85 ? IM_COL32(0xff, 0xb6, 0x48, 255)
                                                                                           : IM_COL32(0xff, 0x6a, 0x55, 255);
   snprintf(t, sizeof(t), "%.1f VI/s", l.frames_per_second);
   dl->AddText(g_osd.display, 34 * u, ImVec2(x + 18 * u, y + 12 * u), IM_COL32(0xe6, 0xf4, 0xf2, 255), t);
   snprintf(t, sizeof(t), "%.0f%%", l.speed);
   const ImVec2 sz = g_osd.display->CalcTextSizeA(34 * u, FLT_MAX, 0, t);
   dl->AddText(g_osd.display, 34 * u, ImVec2(x + w - 18 * u - sz.x, y + 12 * u), speed_colour, t);
   const ImU32 dim = IM_COL32(0xa3, 0xc2, 0xbe, 255), text = IM_COL32(0xe6, 0xf4, 0xf2, 255);
   float ly = y + 60 * u;
   auto line = [&](const char *s, ImU32 c) {
      dl->AddText(g_osd.mono, 15 * u, ImVec2(x + 18 * u, ly), c, s);
      ly += 21 * u;
   };
   snprintf(t, sizeof(t), "game %u fps \xC2\xB7 %s, %u VI/s", l.game_fps, l.target_vis == 50 ? "PAL" : "NTSC", l.target_vis);
   line(t, dim);
   if (l.cpu_ms >= 0)
      snprintf(t, sizeof(t), "CPU %.2f ms \xC2\xB7 present %.2f ms a VI", l.cpu_ms, l.present_ms);
   else
      snprintf(t, sizeof(t), "present %.2f ms a VI", l.present_ms);
   line(t, text);
   snprintf(t, sizeof(t), "RDRAM sync %.2f ms a VI (%.1f)", l.rdram_ms, l.rdram_waits);
   line(t, text);
   snprintf(t, sizeof(t), "audio queue %llu \xC2\xB7 %llu underrun(s)", l.audio_queue, l.audio_underruns);
   line(t, l.audio_underruns ? IM_COL32(0xff, 0xb6, 0x48, 255) : text);
   /* the frame times: a bar a VI, the target's line */
   const float gx = x + 18 * u, gy = y + h - 16 * u, gw = w - 36 * u, gh = 56 * u;
   const float target = l.target_vis ? 1000.0f / l.target_vis : 16.68f, top = target * 2.5f;
   const float bw = gw / 180;
   for (int i = 0; i < n; i++) {
      const float v = std::min(hist[i], top), bh = gh * v / top;
      const ImU32 c = hist[i] > target * 1.5f ? IM_COL32(0xff, 0x6a, 0x55, 230) : IM_COL32(0x4f, 0xf0, 0xe0, 200);
      dl->AddRectFilled(ImVec2(gx + (180 - n + i) * bw, gy - bh), ImVec2(gx + (180 - n + i + 1) * bw - 0.5f * u, gy), c);
   }
   const float ty = gy - gh * target / top;
   dl->AddLine(ImVec2(gx, ty), ImVec2(gx + gw, ty), IM_COL32(214, 236, 232, 90), 1 * u);
   (void)W;
}

