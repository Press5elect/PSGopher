/*
 * PSGopher - the in-game quick menu: the Live Board's LIVE panel over the running game.
 *
 * A touch pad tap (alone: with another button it is Gopher64's hotkey) opens it, between two
 * frames: parallel-rdp's interface calls psgopher_quickmenu_wanted after each present and, when it
 * says yes, psgopher_quickmenu_run, on the emulation thread, so the game is paused while the menu
 * is up. The menu is Dear ImGui; its triangles are drawn over the game's last frame by the
 * interface with parallel-rdp's own device (psgopher_overlay_*, vendor/gopher64/parallel-rdp/
 * interface.cpp, PSGOPHER). What is chosen goes back as Gopher64's own callbacks: save or load a
 * state in a slot ("probes", as the board calls them), reset, quit to the game list.
 *
 * The pad: player 1's. Up/down move, Cross chooses, Circle (or another tap) goes back.
 *
 * SPDX-License-Identifier: GPL-3.0-or-later
 */
