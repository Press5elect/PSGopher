constexpr int kProbes = 5; /* state slots 1-5 (Gopher64's own slot 0 stays its hotkey's) */

/* the Live Board's colours */
const ImU32 kTeal = IM_COL32(0x4f, 0xe3, 0xd0, 255);
const ImU32 kWhite = IM_COL32(0xee, 0xf6, 0xf5, 255);
const ImU32 kDim = IM_COL32(0x8c, 0xa3, 0xa5, 255);
const ImU32 kCard = IM_COL32(0x0b, 0x17, 0x1a, 236);
const ImU32 kCardEdge = IM_COL32(0x2a, 0x4a, 0x4e, 255);
const ImU32 kRow = IM_COL32(0x10, 0x22, 0x26, 255);
const ImU32 kRowEdge = IM_COL32(0x24, 0x3f, 0x43, 255);
const ImU32 kChosen = IM_COL32(0xe6, 0xf4, 0xf2, 255);
const ImU32 kChosenText = IM_COL32(0x07, 0x12, 0x14, 255);

struct Fonts {
   ImFont *text = nullptr, *mono = nullptr, *title = nullptr;
};


/* "today 21:08", "yesterday 21:08", "12 Nov 21:08" */
std::string when(time_t t)
{
   struct tm then = {}, now_tm = {};
   const time_t now = time(nullptr);
   localtime_r(&t, &then);
   localtime_r(&now, &now_tm);
   char hm[16], text[48];
   strftime(hm, sizeof(hm), "%H:%M", &then);
   const int days = (int)((now - t) / 86400);
   if (then.tm_yday == now_tm.tm_yday && then.tm_year == now_tm.tm_year)
      snprintf(text, sizeof(text), "today %s", hm);
   else if (days <= 1)
      snprintf(text, sizeof(text), "yesterday %s", hm);
   else {
      char date[24];
      strftime(date, sizeof(date), "%d %b", &then);
      snprintf(text, sizeof(text), "%s %s", date, hm);
   }
   return text;
}

struct Probe {
   bool kept = false;
   time_t at = 0;
};

enum class Page { Main, Take, Load };

struct QuickMenu {
   Fonts fonts;
   std::string name, states;
   Probe probes[kProbes + 1];
   Page page = Page::Main;
   int cursor = 0;
   bool stats_on = false;
   bool done = false;
   psgopher_quickmenu_answer answer = { 0, 0 };

   void readProbes()
   {
      for (int slot = 1; slot <= kProbes; slot++) {
         struct stat st;
         const std::string path = states + std::to_string(slot);
         probes[slot].kept = !states.empty() && stat(path.c_str(), &st) == 0;
         probes[slot].at = probes[slot].kept ? st.st_mtime : 0;
      }
   }
   int kept() const
   {
      int n = 0;
      for (int slot = 1; slot <= kProbes; slot++)
         n += probes[slot].kept;
      return n;
   }
   void finish(int action, int slot = 0)
   {
      answer = { action, slot };
      done = true;
   }
   void draw(const struct pad &p, float scale);
};

/* a row of the panel: label at the left, a quiet hint at the right; the chosen one is light */
bool row(ImDrawList *dl, const Fonts &f, ImVec2 at, float width, float height, const char *label, const char *hint,
         bool chosen, bool enabled, float scale)
{
   const ImVec2 end(at.x + width, at.y + height);
   dl->AddRectFilled(at, end, chosen ? kChosen : kRow, 8 * scale);
   if (!chosen)
      dl->AddRect(at, end, kRowEdge, 8 * scale, 1.5f * scale);
   const float text = 26 * scale, small = 17 * scale;
   const ImU32 colour = chosen ? kChosenText : enabled ? kWhite : kDim;
   dl->AddText(f.mono, text, ImVec2(at.x + 22 * scale, at.y + (height - text) * 0.5f), colour, label);
   if (hint && *hint) {
      const ImVec2 size = f.mono->CalcTextSizeA(small, FLT_MAX, 0, hint);
      dl->AddText(f.mono, small, ImVec2(end.x - 22 * scale - size.x, at.y + (height - small) * 0.5f),
                  chosen ? IM_COL32(0x2a, 0x3a, 0x3c, 255) : kDim, hint);
   }
   return chosen;
}

void QuickMenu::draw(const struct pad &p, float scale)
{
   ImGuiIO &io = ImGui::GetIO();
   ImDrawList *dl = ImGui::GetForegroundDrawList();
   const float W = io.DisplaySize.x, H = io.DisplaySize.y;

   /* the game dimmed, more towards the panel (the LIVE view's dusk) */
   dl->AddRectFilledMultiColor(ImVec2(0, 0), ImVec2(W, H), IM_COL32(2, 8, 10, 90), IM_COL32(2, 8, 10, 200),
                               IM_COL32(2, 8, 10, 200), IM_COL32(2, 8, 10, 90));

   /* what this page lists */
   struct Item {
      std::string label, hint;
      bool enabled;
      int action, slot;
   };
   std::vector<Item> items;
   std::string eyebrow;
   if (page == Page::Main) {
      eyebrow = "RUNNING  \xC2\xB7  PAUSED BY YOU";
      items.push_back({ "Resume", "tap", true, 0, 0 });
      items.push_back({ "Take a memory probe", "save state", true, -1, 0 });
      char kept_text[24];
      snprintf(kept_text, sizeof(kept_text), "%d kept", kept());
      items.push_back({ "Load a probe", kept_text, kept() > 0, -2, 0 });
      items.push_back({ "Stats overlay", stats_on ? "on" : "off", true, -4, 0 });
      items.push_back({ "Press reset", "the board's button", true, 3, 0 });
      items.push_back({ "Eject cartridge", "back to the board", true, 4, 0 });
   } else {
      eyebrow = page == Page::Take ? "TAKE A MEMORY PROBE  \xC2\xB7  SAVE STATE" : "LOAD A PROBE  \xC2\xB7  LOAD STATE";
      for (int slot = 1; slot <= kProbes; slot++) {
         const Probe &pr = probes[slot];
         const std::string label = "Probe " + std::to_string(slot);
         const std::string hint = pr.kept ? (page == Page::Take ? "replace " : "") + when(pr.at) : "empty";
         items.push_back({ label, hint, page == Page::Take || pr.kept, page == Page::Take ? 1 : 2, slot });
      }
      items.push_back({ "Back", "circle", true, -3, 0 });
   }
   const int n = (int)items.size();
   cursor = std::clamp(cursor, 0, n - 1);

   /* the pad */
   if (p.pressed & PAD_DOWN)
      cursor = (cursor + 1) % n;
   if (p.pressed & PAD_UP)
      cursor = (cursor + n - 1) % n;
   if (p.pressed & PAD_CIRCLE) {
      if (page == Page::Main)
         finish(0);
      else {
         page = Page::Main;
         cursor = 0;
      }
   } else if ((p.pressed & PAD_CROSS) && items[cursor].enabled) {
      const Item &it = items[cursor];
      if (it.action == -1 || it.action == -2) {
         page = it.action == -1 ? Page::Take : Page::Load;
         cursor = 0;
         if (page == Page::Load) /* the newest first */
            for (int slot = 1, best = 0; slot <= kProbes; slot++)
               if (probes[slot].kept && probes[slot].at >= best) {
                  best = (int)probes[slot].at;
                  cursor = slot - 1;
               }
      } else if (it.action == -3) {
         page = Page::Main;
         cursor = 0;
      } else if (it.action == -4) {
         stats_on = !stats_on;
         psgopher::TitleSettings t;
         t.load();
         t.stats = stats_on;
         t.save();
      } else
         finish(it.action, it.slot);
   }

   /* the panel, at the right as on the board */
   const float pw = 640 * scale, pad = 34 * scale, rh = 58 * scale, gap = 12 * scale;
   const float title_size = 58 * scale;
   const float ph = pad * 2 + 22 * scale + 16 * scale + title_size + 26 * scale + n * (rh + gap);
   const ImVec2 p0(W - pw - 96 * scale, std::max(80 * scale, (H - ph) * 0.42f));
   const ImVec2 p1(p0.x + pw, p0.y + ph);
   dl->AddRectFilled(ImVec2(p0.x + 6 * scale, p0.y + 14 * scale), ImVec2(p1.x + 6 * scale, p1.y + 18 * scale),
                     IM_COL32(0, 0, 0, 90), 22 * scale);
   dl->AddRectFilled(p0, p1, kCard, 20 * scale);
   dl->AddRect(p0, p1, kCardEdge, 20 * scale, 2 * scale);
   float y = p0.y + pad;
   dl->AddText(fonts.mono, 18 * scale, ImVec2(p0.x + pad, y), kTeal, eyebrow.c_str());
   y += 22 * scale + 16 * scale;
   const std::string title = name.empty() ? "This cartridge" : name;
   dl->PushClipRect(ImVec2(p0.x + pad, y), ImVec2(p1.x - pad, y + title_size * 1.3f), true);
   dl->AddText(fonts.title, title_size, ImVec2(p0.x + pad, y), kWhite, title.c_str());
   dl->PopClipRect();
   y += title_size + 26 * scale;
   for (int i = 0; i < n; i++) {
      row(dl, fonts, ImVec2(p0.x + pad, y), pw - pad * 2, rh, items[i].label.c_str(), items[i].hint.c_str(), i == cursor,
          items[i].enabled, scale);
      y += rh + gap;
   }

   /* the live strip, at the bottom left as on the board: what the machine was doing a moment ago */
   struct psgopher_live live = {};
   psgopher_live_read(&live);
   psgopher_sdl3_audio_stats audio = {};
   psgopher_sdl3_audio_stats_read(&audio);
   char a[32], b[32], c[32], d[32];
   snprintf(a, sizeof(a), "%.2f", live.frames_per_second);
   if (live.cpu_ms >= 0)
      snprintf(b, sizeof(b), "%.1f", live.cpu_ms);
   else
      snprintf(b, sizeof(b), "-");
   snprintf(c, sizeof(c), "%.1f", live.present_ms);
   snprintf(d, sizeof(d), "%llu", (unsigned long long)audio.queued_frames);
   const char *values[] = { a, b, c, d };
   const char *labels[] = { "FRAMES / S", "CPU THREAD MS", "PRESENT WAIT MS", "AUDIO QUEUE FRAMES" };
   float x = 96 * scale;
   const float bw = 270 * scale, bh = 128 * scale, by = H - bh - 72 * scale;
   for (int i = 0; i < 4; i++) {
      const ImVec2 q0(x, by), q1(x + bw, by + bh);
      dl->AddRectFilled(q0, q1, kCard, 12 * scale);
      dl->AddRect(q0, q1, kCardEdge, 12 * scale, 1.5f * scale);
      dl->AddText(fonts.title, 44 * scale, ImVec2(x + 22 * scale, by + 18 * scale), kWhite, values[i]);
      dl->AddText(fonts.mono, 16 * scale, ImVec2(x + 22 * scale, by + 82 * scale), kDim, labels[i]);
      x += bw + 18 * scale;
   }
   const char *keys = "UP DOWN  MOVE      CROSS  CHOOSE      CIRCLE  BACK      TOUCH PAD  RESUME";
   dl->AddText(fonts.mono, 17 * scale, ImVec2(96 * scale, H - 48 * scale), kDim, keys);
}

/* ImGui's textures (the font atlas) to the interface's, by id */
void updateTextures(ImDrawData *data)
{
   if (!data->Textures)
      return;
   for (ImTextureData *tex : *data->Textures) {
      if (tex->Status == ImTextureStatus_WantCreate || tex->Status == ImTextureStatus_WantUpdates) {
         static uint32_t next_id = 1;
         uint32_t id = (uint32_t)tex->GetTexID();
         if (id == 0)
            id = next_id++;
         /* the whole texture again: a font atlas grows rarely, and the menu is up for seconds */
         if (psgopher_overlay_texture(id, tex->Width, tex->Height, tex->GetPixels()) == 0) {
            tex->SetTexID((ImTextureID)id);
            tex->SetStatus(ImTextureStatus_OK);
         }
      } else if (tex->Status == ImTextureStatus_WantDestroy) {
         psgopher_overlay_texture_free((uint32_t)tex->GetTexID());
         tex->SetTexID(ImTextureID_Invalid);
         tex->SetStatus(ImTextureStatus_Destroyed);
      }
   }
}

void present(ImDrawData *data)
{
   static std::vector<psgopher_overlay_vertex> vertices;
   static std::vector<uint32_t> indices;
   static std::vector<psgopher_overlay_command> commands;
   vertices.clear();
   indices.clear();
   commands.clear();
   for (const ImDrawList *list : data->CmdLists) {
      const uint32_t vbase = (uint32_t)vertices.size(), ibase = (uint32_t)indices.size();
      vertices.resize(vbase + list->VtxBuffer.Size);
      memcpy(&vertices[vbase], list->VtxBuffer.Data, list->VtxBuffer.Size * sizeof(ImDrawVert));
      for (const ImDrawIdx index : list->IdxBuffer)
         indices.push_back(index);
      for (const ImDrawCmd &cmd : list->CmdBuffer) {
         if (cmd.UserCallback || cmd.ElemCount == 0)
            continue;
         commands.push_back({ { cmd.ClipRect.x, cmd.ClipRect.y, cmd.ClipRect.z, cmd.ClipRect.w },
                              (uint32_t)cmd.GetTexID(), ibase + cmd.IdxOffset, cmd.ElemCount,
                              (int32_t)(vbase + cmd.VtxOffset) });
      }
   }
   psgopher_overlay_present(vertices.data(), (uint32_t)vertices.size(), indices.data(), (uint32_t)indices.size(),
                            commands.data(), (uint32_t)commands.size());
}

