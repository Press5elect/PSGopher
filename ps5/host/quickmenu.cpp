/* Called by the interface while it draws each frame: the overlay's triangles when it is on */
extern "C" int psgopher_osd_frame(void)
{
   if (g_osd_wanted < 0) {
      psgopher::TitleSettings t;
      t.load();
      g_osd_wanted = t.stats ? 1 : 0;
   }
   if (!g_osd_wanted)
      return 0;
   ImGuiContext *previous = ImGui::GetCurrentContext();
   if (!g_osd.context) {
      g_osd.context = ImGui::CreateContext();
      ImGui::SetCurrentContext(g_osd.context);
      ImGuiIO &io = ImGui::GetIO();
      io.IniFilename = nullptr;
      io.LogFilename = nullptr;
      io.BackendFlags |= ImGuiBackendFlags_RendererHasTextures | ImGuiBackendFlags_RendererHasVtxOffset;
      ImFontConfig fc;
      fc.FontDataOwnedByAtlas = false;
      g_osd.mono = io.Fonts->AddFontFromMemoryTTF((void *)font_mono, (int)font_mono_size, 20.0f, &fc);
      g_osd.display = io.Fonts->AddFontFromMemoryTTF((void *)font_bricolage, (int)font_bricolage_size, 26.0f, &fc);
   }
   ImGui::SetCurrentContext(g_osd.context);
   ImGuiIO &io = ImGui::GetIO();
   int w = 0, h = 0;
   psgopher_overlay_size(&w, &h);
   io.DisplaySize = ImVec2((float)(w > 0 ? w : 3840), (float)(h > 0 ? h : 2160));
   io.DeltaTime = 1.0f / 60;
   ImGui::NewFrame();
   osdDraw(io.DisplaySize.x, io.DisplaySize.y);
   ImGui::Render();
   updateTextures(ImGui::GetDrawData());
   /* the triangles, kept until the interface has drawn them (this frame) */
   static std::vector<psgopher_overlay_vertex> vertices;
   static std::vector<uint32_t> indices;
   static std::vector<psgopher_overlay_command> commands;
   vertices.clear();
   indices.clear();
   commands.clear();
   for (const ImDrawList *list : ImGui::GetDrawData()->CmdLists) {
      const uint32_t vbase = (uint32_t)vertices.size(), ibase = (uint32_t)indices.size();
      vertices.resize(vbase + list->VtxBuffer.Size);
      memcpy(&vertices[vbase], list->VtxBuffer.Data, list->VtxBuffer.Size * sizeof(ImDrawVert));
      for (const ImDrawIdx index : list->IdxBuffer)
         indices.push_back(index);
      for (const ImDrawCmd &cmd : list->CmdBuffer)
         if (!cmd.UserCallback && cmd.ElemCount)
            commands.push_back({ { cmd.ClipRect.x, cmd.ClipRect.y, cmd.ClipRect.z, cmd.ClipRect.w }, (uint32_t)cmd.GetTexID(),
                                 ibase + cmd.IdxOffset, cmd.ElemCount, (int32_t)(vbase + cmd.VtxOffset) });
   }
   ImGui::SetCurrentContext(previous);
   if (commands.empty())
      return 0;
   psgopher_overlay_set(vertices.data(), (uint32_t)vertices.size(), indices.data(), (uint32_t)indices.size(), commands.data(),
                        (uint32_t)commands.size());
   return 1;
}

/* The game ends (the interface's textures go): the overlay's context with them */
extern "C" void psgopher_osd_release(void)
{
   if (!g_osd.context)
      return;
   ImGuiContext *previous = ImGui::GetCurrentContext();
   ImGui::DestroyContext(g_osd.context);
   ImGui::SetCurrentContext(previous == g_osd.context ? nullptr : previous);
   g_osd = Osd{};
   g_osd_wanted = -1;
}
