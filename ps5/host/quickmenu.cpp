extern "C" int psgopher_quickmenu_wanted(void)
{
   return psgopher_sdl3_take_tap();
}

extern "C" psgopher_quickmenu_answer psgopher_quickmenu_run(void)
{
   QuickMenu menu;
   char name[64] = {}, states[512] = {};
   psgopher_game_info(name, sizeof(name), states, sizeof(states));
   menu.name = name;
   menu.states = states;
   menu.readProbes();
   {
      psgopher::TitleSettings t;
      t.load();
      menu.stats_on = t.stats;
   }
   psgopher_sdl3_audio_hold(1); /* the game is paused: the audio's underruns are not counted meanwhile */
   say("quickmenu: open (%s; %d probe(s) kept)", name[0] ? name : "no name", menu.kept());

   ImGuiContext *previous = ImGui::GetCurrentContext();
   ImGuiContext *context = ImGui::CreateContext();
   ImGui::SetCurrentContext(context);
   ImGuiIO &io = ImGui::GetIO();
   io.IniFilename = nullptr;
   io.LogFilename = nullptr;
   io.BackendFlags |= ImGuiBackendFlags_RendererHasTextures | ImGuiBackendFlags_RendererHasVtxOffset;
   int w = 0, h = 0;
   psgopher_overlay_size(&w, &h);
   if (w <= 0 || h <= 0)
      w = 3840, h = 2160;
   const float scale = (float)h / 1080.0f;
   ImFontConfig fc;
   fc.FontDataOwnedByAtlas = false;
   menu.fonts.mono = io.Fonts->AddFontFromMemoryTTF((void *)font_mono, (int)font_mono_size, 20.0f, &fc);
   menu.fonts.title = io.Fonts->AddFontFromMemoryTTF((void *)font_bricolage, (int)font_bricolage_size, 26.0f, &fc);
   menu.fonts.text = menu.fonts.mono;

   /* the Cross or tap that opened it is not a choice: input once all is let go */
   bool released = false;
   double last = now_seconds();
   /* kept from frame to frame: the pad layer's "pressed" is what went down since the held buttons
    * this holds (a pad read afresh each frame made a press of two frames two presses) */
   struct pad p = {};
   while (!menu.done) {
      psgopher_sdl3_menu_pad(&p);
      if (!released)
         released = p.held == 0;
      if (!released)
         p.pressed = 0;
      else if (psgopher_sdl3_take_tap())
         menu.finish(0); /* another tap: back to the game */
      const double now = now_seconds();
      io.DeltaTime = (float)std::max(1e-3, now - last);
      last = now;
      io.DisplaySize = ImVec2((float)w, (float)h);
      ImGui::NewFrame();
      menu.draw(p, scale);
      ImGui::Render();
      updateTextures(ImGui::GetDrawData());
      present(ImGui::GetDrawData());
   }
   /* the font atlas's textures go with the context */
   for (ImTextureData *tex : ImGui::GetPlatformIO().Textures)
      if (tex->GetTexID() != ImTextureID_Invalid)
         psgopher_overlay_texture_free((uint32_t)tex->GetTexID());
   ImGui::DestroyContext(context);
   ImGui::SetCurrentContext(previous);
   psgopher_sdl3_hold_until_released();
   psgopher_sdl3_audio_hold(0);
   extern int g_osd_wanted;
   g_osd_wanted = menu.stats_on ? 1 : 0;
   static const char *const names[] = { "resume", "save state", "load state", "reset", "quit" };
   say("quickmenu: %s%s", names[std::clamp(menu.answer.action, 0, 4)],
       menu.answer.action == 1 || menu.answer.action == 2 ? (" (probe " + std::to_string(menu.answer.slot) + ")").c_str() : "");
   return menu.answer;
}

