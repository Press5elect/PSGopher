bool openDisplay(Display &d)
{
	volkInitializeCustom((PFN_vkGetInstanceProcAddr)SDL_Vulkan_GetVkGetInstanceProcAddr());
	Uint32 extensionCount = 0;
	const char *const *extensions = SDL_Vulkan_GetInstanceExtensions(&extensionCount);
	VkApplicationInfo app{ VK_STRUCTURE_TYPE_APPLICATION_INFO };
	app.pApplicationName = "PSGopher";
	app.apiVersion = VK_API_VERSION_1_3;
	VkInstanceCreateInfo ii{ VK_STRUCTURE_TYPE_INSTANCE_CREATE_INFO };
	ii.pApplicationInfo = &app;
	ii.enabledExtensionCount = extensionCount;
	ii.ppEnabledExtensionNames = extensions;
	VkResult r = vkCreateInstance(&ii, nullptr, &d.instance);
	if (r != VK_SUCCESS)
		return fail("vkCreateInstance", r);
	volkLoadInstance(d.instance);
	uint32_t gpus = 1;
	if ((r = vkEnumeratePhysicalDevices(d.instance, &gpus, &d.gpu)) < 0 || gpus == 0)
		return fail("no GPU", r);
	d.window = SDL_CreateWindow("PSGopher", 0, 0, SDL_WINDOW_VULKAN | SDL_WINDOW_FULLSCREEN);
	if (!d.window || !SDL_Vulkan_CreateSurface(d.window, d.instance, nullptr, &d.surface))
		return fail(SDL_GetError());
	uint32_t families = 0;
	vkGetPhysicalDeviceQueueFamilyProperties(d.gpu, &families, nullptr);
	std::vector<VkQueueFamilyProperties> props(families);
	vkGetPhysicalDeviceQueueFamilyProperties(d.gpu, &families, props.data());
	for (uint32_t i = 0; i < families; i++) {
		VkBool32 present = VK_FALSE;
		vkGetPhysicalDeviceSurfaceSupportKHR(d.gpu, i, d.surface, &present);
		if ((props[i].queueFlags & VK_QUEUE_GRAPHICS_BIT) && present) {
			d.family = i;
			break;
		}
	}
	const float priority = 1.0f;
	VkDeviceQueueCreateInfo qi{ VK_STRUCTURE_TYPE_DEVICE_QUEUE_CREATE_INFO };
	qi.queueFamilyIndex = d.family;
	qi.queueCount = 1;
	qi.pQueuePriorities = &priority;
	const char *deviceExtensions[] = { VK_KHR_SWAPCHAIN_EXTENSION_NAME };
	VkDeviceCreateInfo di{ VK_STRUCTURE_TYPE_DEVICE_CREATE_INFO };
	di.queueCreateInfoCount = 1;
	di.pQueueCreateInfos = &qi;
	di.enabledExtensionCount = 1;
	di.ppEnabledExtensionNames = deviceExtensions;
	if ((r = vkCreateDevice(d.gpu, &di, nullptr, &d.device)) != VK_SUCCESS)
		return fail("vkCreateDevice", r);
	volkLoadDevice(d.device);
	vkGetDeviceQueue(d.device, d.family, 0, &d.queue);

	VkSurfaceCapabilitiesKHR caps{};
	vkGetPhysicalDeviceSurfaceCapabilitiesKHR(d.gpu, d.surface, &caps);
	uint32_t formats = 0;
	vkGetPhysicalDeviceSurfaceFormatsKHR(d.gpu, d.surface, &formats, nullptr);
	std::vector<VkSurfaceFormatKHR> fmts(formats);
	vkGetPhysicalDeviceSurfaceFormatsKHR(d.gpu, d.surface, &formats, fmts.data());
	VkSurfaceFormatKHR chosen = fmts.empty() ? VkSurfaceFormatKHR{ VK_FORMAT_B8G8R8A8_UNORM, VK_COLOR_SPACE_SRGB_NONLINEAR_KHR } : fmts[0];
	for (const auto &f : fmts) /* ImGui's colours are meant as they are written: a UNORM target */
		if (f.format == VK_FORMAT_B8G8R8A8_UNORM || f.format == VK_FORMAT_R8G8B8A8_UNORM) {
			chosen = f;
			break;
		}
	d.format = chosen.format;
	d.extent = caps.currentExtent.width != UINT32_MAX ? caps.currentExtent : VkExtent2D{ 3840, 2160 };
	uint32_t count = std::max(caps.minImageCount, 2u);
	if (caps.maxImageCount && count > caps.maxImageCount)
		count = caps.maxImageCount;
	VkSwapchainCreateInfoKHR si{ VK_STRUCTURE_TYPE_SWAPCHAIN_CREATE_INFO_KHR };
	si.surface = d.surface;
	si.minImageCount = count;
	si.imageFormat = chosen.format;
	si.imageColorSpace = chosen.colorSpace;
	si.imageExtent = d.extent;
	si.imageArrayLayers = 1;
	si.imageUsage = VK_IMAGE_USAGE_COLOR_ATTACHMENT_BIT;
	si.preTransform = VK_SURFACE_TRANSFORM_IDENTITY_BIT_KHR;
	si.compositeAlpha = VK_COMPOSITE_ALPHA_OPAQUE_BIT_KHR;
	si.presentMode = VK_PRESENT_MODE_FIFO_KHR; /* the console's one mode */
	si.clipped = VK_TRUE;
	if ((r = vkCreateSwapchainKHR(d.device, &si, nullptr, &d.swapchain)) != VK_SUCCESS)
		return fail("vkCreateSwapchainKHR", r);
	vkGetSwapchainImagesKHR(d.device, d.swapchain, &count, nullptr);
	d.images.resize(count);
	vkGetSwapchainImagesKHR(d.device, d.swapchain, &count, d.images.data());

	if (!makeTargets(d, VK_IMAGE_LAYOUT_PRESENT_SRC_KHR))
		return false;
	say("menu: display %ux%u, format %d, %u images", d.extent.width, d.extent.height, (int)d.format, count);
	return true;
}
