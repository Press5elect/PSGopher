std::string sizeText(uint64_t bytes)
{
	char t[32];
	if (bytes >= (1u << 20))
		snprintf(t, sizeof(t), "%.0f MiB", bytes / 1048576.0);
	else
		snprintf(t, sizeof(t), "%llu KiB", (unsigned long long)(bytes / 1024));
	return t;
}

/* a row: the label on the left, the value at the right edge; Cross (and, for values, left/right)
 * act on it. Returns whether it is the focused row. */
bool row(const char *id, const std::string &label, const std::string &value, bool *activated, ImU32 valueColour = kAccent)
{
	ImGui::PushID(id);
	*activated = ImGui::Selectable("##row", false, 0, ImVec2(0, ImGui::GetFontSize() * 1.6f));
	const bool focused = ImGui::IsItemFocused();
	const ImVec2 min = ImGui::GetItemRectMin(), max = ImGui::GetItemRectMax();
	ImDrawList *dl = ImGui::GetWindowDrawList();
	const float y = min.y + (max.y - min.y - ImGui::GetFontSize()) * 0.5f;
	dl->AddText(ImVec2(min.x + 16, y), ImGui::GetColorU32(ImGuiCol_Text), label.c_str());
	if (!value.empty()) {
		const ImVec2 sz = ImGui::CalcTextSize(value.c_str());
		dl->AddText(ImVec2(max.x - sz.x - 16, y), valueColour, value.c_str());
	}
	ImGui::PopID();
	return focused;
}

