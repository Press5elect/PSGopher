void Menu::drawShareEdit(const Buttons &b)
{
	if (keyboard.open)
		return;
	if (b.pressed & PAD_CIRCLE) {
		go(Screen::Shares);
		return;
	}
	bool act = false;
	heading(editing < 0 ? "A new share" : "The share");
	ImGui::BeginChild("##edit", ImVec2(0, -ImGui::GetFontSize() * 2.4f), ImGuiChildFlags_NavFlattened);
	focusHere();
	if (row("kind", "Kind", draft.nfs ? "NFS" : "SMB (Windows, Samba, most NAS)", &act); act || (ImGui::IsItemFocused() && (b.pressed & (PAD_LEFT | PAD_RIGHT))))
		draft.nfs = !draft.nfs;
	const auto text = [&](const char *id, const char *label, std::string &field, const char *what, bool secret) {
		const std::string shown = field.empty() ? "(none)" : secret ? std::string(field.size(), '*') : field;
		if (row(id, label, shown, &act, field.empty() ? kDim : kAccent); act)
			keyboard.start(what, &field, secret);
	};
	text("host", "Server", draft.host, "The server: its address (192.168.1.10) or name", false);
	if (!draft.nfs) {
		if (row("find", "Find SMB servers on the network", finding ? "Looking..." : "", &act); act && !finding) {
			finding = true;
			foundAsked = true;
			std::thread([] {
				std::vector<FoundServer> f = findServers();
				std::lock_guard lock(foundMutex);
				found = std::move(f);
				finding = false;
			}).detach();
		}
		if (foundAsked && !finding) {
			std::lock_guard lock(foundMutex);
			if (found.empty())
				hint("None answered on port 445.");
			for (size_t i = 0; i < found.size(); i++) {
				ImGui::PushID((int)i + 100);
				if (row("f", "    " + (found[i].name.empty() ? found[i].ip : found[i].name + "  (" + found[i].ip + ")"), "Use", &act); act)
					draft.host = found[i].ip;
				ImGui::PopID();
			}
		}
	}
	text("path", draft.nfs ? "Export and folder" : "Share and folder", draft.path,
		draft.nfs ? "The export and folder: /volume1/games/n64" : "The share and folder: games/n64", false);
	if (!draft.nfs) {
		text("user", "User", draft.user, "The account's user (none: guest)", false);
		text("password", "Password", draft.password, "The account's password", true);
	}
	text("name", "Name", draft.name, "The share's name in the list", false);
	ImGui::Dummy(ImVec2(0, 10));
	if (row("save", editing < 0 ? "Add and mount it" : "Save and mount it again", "", &act); act) {
		if (draft.host.empty() || draft.path.empty())
			tell("A share needs its server and its share or export.");
		else {
			if (draft.name.empty())
				draft.name = shareDefaultName(draft);
			std::vector<std::string> taken;
			for (size_t i = 0; i < shares.shares.size(); i++)
				if ((int)i != editing && !shares.shares[i].mount.empty())
					taken.push_back(shares.shares[i].mount);
			if (editing >= 0)
				unmountShare(shares.shares[editing]);
			std::string error;
			Share s = draft;
			s.mount.clear();
			const bool mounted = mountShare(s, shares, taken, &error);
			if (editing >= 0)
				shares.shares[editing] = s;
			else
				shares.shares.push_back(s);
			saveShares();
			tell(mounted ? s.name + " is mounted at " + s.mount + "; searching it for games" : s.name + ": " + error);
			if (mounted)
				library().rescan();
			go(Screen::Shares);
		}
	}
	if (editing >= 0) {
		if (row("remove", "Remove this share", "", &act); act) {
			unmountShare(shares.shares[editing]);
			shares.shares.erase(shares.shares.begin() + editing);
			saveShares();
			library().rescan();
			tell("The share is removed");
			go(Screen::Shares);
		}
	}
	ImGui::EndChild();
	ImGui::Separator();
	hint("Cross edits (an on-screen keyboard)   Circle back without saving");
}

void Menu::draw(const Buttons &b)
{
	const ImGuiViewport *vp = ImGui::GetMainViewport();
	ImGui::SetNextWindowPos(vp->Pos);
	ImGui::SetNextWindowSize(vp->Size);
	ImGui::Begin("##psgopher", nullptr, ImGuiWindowFlags_NoDecoration | ImGuiWindowFlags_NoSavedSettings |
		ImGuiWindowFlags_NoBringToFrontOnFocus | (keyboard.open ? ImGuiWindowFlags_NoNav : 0));
	/* the header: the name, and what was just said */
	ImGui::PushFont(nullptr, ImGui::GetStyle().FontSizeBase * 1.5f);
	ImGui::PushStyleColor(ImGuiCol_Text, kAccent);
	ImGui::TextUnformatted("PSGopher");
	ImGui::PopStyleColor();
	ImGui::PopFont();
	if (!notice.empty() && now_seconds() < noticeUntil) {
		ImGui::SameLine(0, ImGui::GetFontSize() * 2);
		ImGui::TextUnformatted(notice.c_str());
	}
	const Buttons none{};
	const Buttons &input = keyboard.open ? none : b;
	switch (screen) {
	case Screen::List: drawList(input); break;
	case Screen::Settings: drawSettings(input); break;
	case Screen::Shares: drawShares(input); break;
	case Screen::ShareEdit: drawShareEdit(input); break;
	}
	ImGui::End();
	keyboard.draw(b);
}

void frame(Display &d, Menu &menu, const Buttons &b)
{
	vkWaitForFences(d.device, 1, &d.fence[d.frame], VK_TRUE, UINT64_MAX);
	uint32_t image = 0;
#ifndef PSGOPHER_MENU_HOST
	const VkResult acquired = vkAcquireNextImageKHR(d.device, d.swapchain, UINT64_MAX, d.acquired[d.frame], VK_NULL_HANDLE, &image);
	if (acquired != VK_SUCCESS && acquired != VK_SUBOPTIMAL_KHR) {
		say("menu: vkAcquireNextImageKHR %d", (int)acquired);
		usleep(16000);
		return;
	}
#endif
	vkResetFences(d.device, 1, &d.fence[d.frame]);

	ImGui_ImplVulkan_NewFrame();
	ImGuiIO &io = ImGui::GetIO();
	io.DisplaySize = ImVec2((float)d.extent.width, (float)d.extent.height);
	ImGui::NewFrame();
	menu.draw(b);
	ImGui::Render();

	VkCommandBuffer cmd = d.cmd[d.frame];
	vkResetCommandBuffer(cmd, 0);
	VkCommandBufferBeginInfo bi{ VK_STRUCTURE_TYPE_COMMAND_BUFFER_BEGIN_INFO };
	bi.flags = VK_COMMAND_BUFFER_USAGE_ONE_TIME_SUBMIT_BIT;
	vkBeginCommandBuffer(cmd, &bi);
	VkClearValue clear{};
	clear.color = { { 0.035f, 0.075f, 0.085f, 1.0f } };
	VkRenderPassBeginInfo rb{ VK_STRUCTURE_TYPE_RENDER_PASS_BEGIN_INFO };
	rb.renderPass = d.pass;
	rb.framebuffer = d.framebuffers[image];
	rb.renderArea.extent = d.extent;
	rb.clearValueCount = 1;
	rb.pClearValues = &clear;
	vkCmdBeginRenderPass(cmd, &rb, VK_SUBPASS_CONTENTS_INLINE);
	ImGui_ImplVulkan_RenderDrawData(ImGui::GetDrawData(), cmd);
	vkCmdEndRenderPass(cmd);
#ifdef PSGOPHER_MENU_HOST
	const bool shot = psgopher_menu_host_shot != nullptr;
	if (shot) {
		VkBufferImageCopy copy{};
		copy.imageSubresource = { VK_IMAGE_ASPECT_COLOR_BIT, 0, 0, 1 };
		copy.imageExtent = { d.extent.width, d.extent.height, 1 };
		vkCmdCopyImageToBuffer(cmd, d.images[0], VK_IMAGE_LAYOUT_TRANSFER_SRC_OPTIMAL, d.readback, 1, &copy);
	}
#endif
	vkEndCommandBuffer(cmd);

	const VkPipelineStageFlags wait = VK_PIPELINE_STAGE_COLOR_ATTACHMENT_OUTPUT_BIT;
	VkSubmitInfo si{ VK_STRUCTURE_TYPE_SUBMIT_INFO };
#ifdef PSGOPHER_MENU_HOST
	si.commandBufferCount = 1;
	si.pCommandBuffers = &cmd;
	vkQueueSubmit(d.queue, 1, &si, d.fence[d.frame]);
	vkWaitForFences(d.device, 1, &d.fence[d.frame], VK_TRUE, UINT64_MAX);
	if (shot) {
		void *pixels = nullptr;
		vkMapMemory(d.device, d.readbackMemory, 0, VK_WHOLE_SIZE, 0, &pixels);
		if (FILE *f = fopen(psgopher_menu_host_shot, "wb")) {
			fprintf(f, "P6\n%u %u\n255\n", d.extent.width, d.extent.height);
			const unsigned char *p = (const unsigned char *)pixels;
			std::vector<unsigned char> rgb((size_t)d.extent.width * d.extent.height * 3);
			for (size_t i = 0; i < rgb.size() / 3; i++)
				memcpy(&rgb[i * 3], p + i * 4, 3);
			fwrite(rgb.data(), 1, rgb.size(), f);
			fclose(f);
		}
		vkUnmapMemory(d.device, d.readbackMemory);
		psgopher_menu_host_shot = nullptr;
	}
	d.frame = (d.frame + 1) % Display::kFrames;
	return;
#endif
	si.waitSemaphoreCount = 1;
	si.pWaitSemaphores = &d.acquired[d.frame];
	si.pWaitDstStageMask = &wait;
	si.commandBufferCount = 1;
	si.pCommandBuffers = &cmd;
	si.signalSemaphoreCount = 1;
	si.pSignalSemaphores = &d.rendered[image];
	vkQueueSubmit(d.queue, 1, &si, d.fence[d.frame]);
	VkPresentInfoKHR pi{ VK_STRUCTURE_TYPE_PRESENT_INFO_KHR };
	pi.waitSemaphoreCount = 1;
	pi.pWaitSemaphores = &d.rendered[image];
	pi.swapchainCount = 1;
	pi.pSwapchains = &d.swapchain;
	pi.pImageIndices = &image;
	vkQueuePresentKHR(d.queue, &pi);
	d.frame = (d.frame + 1) % Display::kFrames;
}

