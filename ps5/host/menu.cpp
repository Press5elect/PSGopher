void closeDisplay(Display &d)
{
	if (d.device)
		vkDeviceWaitIdle(d.device);
	if (d.imgui)
		ImGui_ImplVulkan_Shutdown();
	d.imgui = false;
	if (d.device) {
		for (int i = 0; i < Display::kFrames; i++) {
			if (d.fence[i])
				vkDestroyFence(d.device, d.fence[i], nullptr);
			if (d.acquired[i])
				vkDestroySemaphore(d.device, d.acquired[i], nullptr);
		}
		if (d.pool)
			vkDestroyCommandPool(d.device, d.pool, nullptr);
		for (VkSemaphore s : d.rendered)
			vkDestroySemaphore(d.device, s, nullptr);
		for (VkFramebuffer fb : d.framebuffers)
			vkDestroyFramebuffer(d.device, fb, nullptr);
		for (VkImageView v : d.views)
			vkDestroyImageView(d.device, v, nullptr);
		if (d.pass)
			vkDestroyRenderPass(d.device, d.pass, nullptr);
#ifdef PSGOPHER_MENU_HOST
		for (VkImage image : d.images)
			vkDestroyImage(d.device, image, nullptr);
		vkDestroyBuffer(d.device, d.readback, nullptr);
		vkFreeMemory(d.device, d.memory, nullptr);
		vkFreeMemory(d.device, d.readbackMemory, nullptr);
#else
		if (d.swapchain)
			vkDestroySwapchainKHR(d.device, d.swapchain, nullptr);
#endif
		vkDestroyDevice(d.device, nullptr);
	}
#ifndef PSGOPHER_MENU_HOST
	if (d.surface)
		SDL_Vulkan_DestroySurface(d.instance, d.surface, nullptr);
#endif
	if (d.instance)
		vkDestroyInstance(d.instance, nullptr);
#ifndef PSGOPHER_MENU_HOST
	if (d.window)
		SDL_DestroyWindow(d.window);
#endif
	d = Display{};
}

/* ------------------------------------------------------------------ the pad, for ImGui */

struct Buttons {
	uint32_t held{ 0 }, pressed{ 0 };
	bool repeat(uint32_t button, double now) const;
	mutable double heldSince[32]{};
	mutable double lastRepeat[32]{};
};
/* a button held repeats after 0.4 s, every 0.1 s (for the values changed with left and right) */
bool Buttons::repeat(uint32_t button, double now) const
{
	const int bit = __builtin_ctz(button);
	if (pressed & button) {
		heldSince[bit] = lastRepeat[bit] = now;
		return true;
	}
	if ((held & button) && now - heldSince[bit] > 0.4 && now - lastRepeat[bit] > 0.1) {
		lastRepeat[bit] = now;
		return true;
	}
	return false;
}

void feedImGui(const struct pad &p)
{
	ImGuiIO &io = ImGui::GetIO();
	const struct {
		ImGuiKey key;
		uint32_t button;
	} map[] = {
		{ ImGuiKey_GamepadDpadUp, PAD_UP }, { ImGuiKey_GamepadDpadDown, PAD_DOWN },
		{ ImGuiKey_GamepadDpadLeft, PAD_LEFT }, { ImGuiKey_GamepadDpadRight, PAD_RIGHT },
		{ ImGuiKey_GamepadFaceDown, PAD_CROSS },
	};
	for (const auto &m : map)
		io.AddKeyEvent(m.key, (p.held & m.button) != 0);
	const auto axis = [&](ImGuiKey key, float v) { io.AddKeyAnalogEvent(key, v > 0.3f, v > 0.3f ? v : 0.0f); };
	axis(ImGuiKey_GamepadLStickUp, -p.left_y);
	axis(ImGuiKey_GamepadLStickDown, p.left_y);
	axis(ImGuiKey_GamepadLStickLeft, -p.left_x);
	axis(ImGuiKey_GamepadLStickRight, p.left_x);
}

