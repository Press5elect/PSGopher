struct Keyboard {
	bool open{ false };
	bool shift{ false };
	bool secret{ false };
	std::string title, text;
	std::string *target{ nullptr };
	bool focus{ false };

	void start(const std::string &what, std::string *field, bool hidden)
	{
		open = true;
		shift = false;
		secret = hidden;
		title = what;
		target = field;
		text = *field;
		focus = true;
	}
	/* Cross types the key, SQUARE deletes, OPTIONS is done, CIRCLE leaves the text as it was */
	void draw(const Buttons &b)
	{
		if (!open)
			return;
		if (b.pressed & PAD_SQUARE && !text.empty())
			text.pop_back();
		if (b.pressed & PAD_CIRCLE) {
			open = false;
			return;
		}
		if (b.pressed & PAD_OPTIONS) {
			*target = text;
			open = false;
			return;
		}
		const ImGuiViewport *vp = ImGui::GetMainViewport();
		ImGui::SetNextWindowPos(ImVec2(vp->Size.x * 0.5f, vp->Size.y * 0.55f), ImGuiCond_Always, ImVec2(0.5f, 0.5f));
		ImGui::SetNextWindowFocus();
		ImGui::Begin("##keyboard", nullptr, ImGuiWindowFlags_NoDecoration | ImGuiWindowFlags_AlwaysAutoResize | ImGuiWindowFlags_NoSavedSettings);
		ImGui::PushStyleColor(ImGuiCol_Text, kAccent);
		ImGui::TextUnformatted(title.c_str());
		ImGui::PopStyleColor();
		const std::string shown = secret ? std::string(text.size(), '*') : text;
		ImGui::PushStyleColor(ImGuiCol_FrameBg, ImVec4(0.02f, 0.04f, 0.05f, 1));
		ImGui::BeginChild("##text", ImVec2(ImGui::GetFontSize() * 26, ImGui::GetFontSize() * 1.8f), ImGuiChildFlags_FrameStyle);
		ImGui::Text("%s_", shown.c_str());
		ImGui::EndChild();
		ImGui::PopStyleColor();
		static const char *const lowerRows[] = { "1234567890-=", "qwertyuiop[]", "asdfghjkl;'\\", "zxcvbnm,./`" };
		static const char *const upperRows[] = { "!@#$%^&*()_+", "QWERTYUIOP{}", "ASDFGHJKL:\"|", "ZXCVBNM<>?~" };
		const float key = ImGui::GetFontSize() * 2.0f;
		for (int r = 0; r < 4; r++) {
			const char *keys = (shift ? upperRows : lowerRows)[r];
			for (int i = 0; keys[i]; i++) {
				if (i)
					ImGui::SameLine();
				const char label[2] = { keys[i], 0 };
				ImGui::PushID(r * 64 + i);
				if (focus && r == 1 && i == 0) {
					ImGui::SetKeyboardFocusHere();
					focus = false;
				}
				if (ImGui::Button(label, ImVec2(key, key)))
					text += keys[i];
				ImGui::PopID();
			}
		}
		if (ImGui::Button(shift ? "Shift (on)" : "Shift", ImVec2(key * 3, key)))
			shift = !shift;
		ImGui::SameLine();
		if (ImGui::Button("Space", ImVec2(key * 4, key)))
			text += ' ';
		ImGui::SameLine();
		if (ImGui::Button("Delete", ImVec2(key * 2.5f, key)) && !text.empty())
			text.pop_back();
		ImGui::SameLine();
		if (ImGui::Button("Done", ImVec2(key * 2.5f, key))) {
			*target = text;
			open = false;
		}
		hint("Cross types   Square deletes   Options is done   Circle leaves it as it was");
		ImGui::End();
	}
};

