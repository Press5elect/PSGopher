struct Menu {
	Screen screen{ Screen::List };
	int tab{ TabInternal };
	bool focusFirst{ true };
	std::string notice;
	double noticeUntil{ 0 };
	Keyboard keyboard;
	TitleSettings title;
	std::string displayAtStart;
	bool elevationOff{ false };
	MenuResult result;
	bool done{ false };
	/* shares */
	ShareFile shares;
	int editing{ -1 }; // the share being edited, -1 a new one
	Share draft;
	bool foundAsked{ false };

	void tell(const std::string &text, double seconds = 6)
	{
		notice = text;
		noticeUntil = now_seconds() + seconds;
	}
	void go(Screen s)
	{
		screen = s;
		focusFirst = true;
	}
	void focusHere()
	{
		if (focusFirst) {
			ImGui::SetKeyboardFocusHere();
			focusFirst = false;
		}
	}
	/* Gopher64's settings, read once (each read is config.json) and written through */
	std::vector<std::pair<std::string, int64_t>> cache;
	int64_t get(const std::string &key)
	{
		for (auto &kv : cache)
			if (kv.first == key)
				return kv.second;
		cache.emplace_back(key, psgopher_setting_get(key.c_str()));
		return cache.back().second;
	}
	void set(const std::string &key, int64_t value)
	{
		if (!psgopher_setting_set(key.c_str(), value)) {
			tell("Gopher64 did not take " + key);
			return;
		}
		for (auto &kv : cache)
			if (kv.first == key)
				kv.second = value;
	}
	std::string focusedPath;
	void draw(const Buttons &b);
	void drawList(const Buttons &b);
	void drawSettings(const Buttons &b);
	void drawShares(const Buttons &b);
	void drawShareEdit(const Buttons &b);
	void play(const Game &g);
	void saveShares();
};

void Menu::play(const Game &g)
{
	result.name = g.name;
	if (g.tab != TabNetwork) {
		result.play = true;
		result.rom = g.path;
		done = true;
		return;
	}
	/* a share's: copied on a thread while the list says so */
	if (g_copy.state.exchange(1) == 1)
		return;
	{
		std::lock_guard lock(g_copy.mutex);
		g_copy.name = g.name;
	}
	tell("Copying " + g.name + " from the share...", 600);
	std::thread([path = g.path] {
		std::string error;
		const std::string local = localCopy(path, &error);
		std::lock_guard lock(g_copy.mutex);
		g_copy.local = local;
		g_copy.error = error;
		g_copy.state = 2;
	}).detach();
}

void Menu::drawList(const Buttons &input)
{
	if (g_copy.state == 2) {
		std::lock_guard lock(g_copy.mutex);
		g_copy.state = 0;
		if (g_copy.local.empty())
			tell(g_copy.name + ": " + g_copy.error);
		else {
			result.play = true;
			result.rom = g_copy.local;
			done = true;
		}
	}
	const Buttons none{};
	const Buttons &b = g_copy.state == 1 ? none : input; /* nothing else while a copy runs */
	if (b.pressed & PAD_L1)
		tab = (tab + TabCount - 1) % TabCount, focusFirst = true;
	if (b.pressed & PAD_R1)
		tab = (tab + 1) % TabCount, focusFirst = true;
	if (b.pressed & PAD_TRIANGLE) {
		library().rescan();
		tell("Searching every place for games again");
	}
	if (b.pressed & PAD_OPTIONS) {
		go(Screen::Settings);
		return;
	}
	if ((b.pressed & PAD_SQUARE) && tab == TabNetwork) {
		go(Screen::Shares);
		return;
	}

	/* the tabs */
	ImDrawList *dl = ImGui::GetWindowDrawList();
	for (int t = 0; t < TabCount; t++) {
		if (t)
			ImGui::SameLine(0, ImGui::GetFontSize() * 1.5f);
		ImGui::PushStyleColor(ImGuiCol_Text, t == tab ? kAccent : kDim);
		ImGui::TextUnformatted(tabName(t));
		ImGui::PopStyleColor();
		if (t == tab) {
			const ImVec2 min = ImGui::GetItemRectMin(), max = ImGui::GetItemRectMax();
			dl->AddRectFilled(ImVec2(min.x, max.y + 4), ImVec2(max.x, max.y + 8), kAccent);
		}
	}
	ImGui::SameLine(0, ImGui::GetFontSize() * 1.5f);
	hint("L1 / R1");
	ImGui::Separator();

	const std::vector<Game> games = library().games();
	std::vector<const Game *> shown;
	for (const Game &g : games)
		if (g.tab == tab)
			shown.push_back(&g);
	const float footer = ImGui::GetFontSize() * 2.4f;
	ImGui::BeginChild("##games", ImVec2(0, -footer), ImGuiChildFlags_NavFlattened);
	if (tab == TabNetwork) {
		if (shares.shares.empty())
			hint("No network shares yet: press Square to add one (SMB or NFS).");
		else {
			std::string line = "Shares:";
			for (const Share &s : shares.shares)
				line += "  " + s.name + (s.mount.empty() ? " (not mounted)" : "");
			hint((line + "   (Square: manage)").c_str());
		}
	}
	if (tab == TabUsb && !psgopher_sandbox_elevated())
		hint("USB drives are outside the title's sandbox, and PSGopher did not leave it at this start "
			"(Settings > Storage says why).");
	if (shown.empty()) {
		hint(library().scanning() ? "Looking for games..." : "No games here. ROMs (.z64 .n64 .v64, and .zip/.7z of one) are found "
			"on the console, USB drives and network shares a few folders deep; Triangle searches again.");
	}
	for (size_t i = 0; i < shown.size(); i++) {
		const Game &g = *shown[i];
		if (i == 0)
			focusHere();
		bool chosen = false;
		ImGui::PushID((int)i);
		row("g", g.name, sizeText(g.size), &chosen, kDim);
		if (ImGui::IsItemFocused())
			focusedPath = g.path;
		ImGui::PopID();
		if (chosen && g_copy.state != 1) {
			play(g);
			break;
		}
	}
	ImGui::EndChild();
	ImGui::Separator();
	std::string foot = "Cross Play     Triangle Search again     Options Settings     In a game: hold the touch pad + Options: back here";
	if (tab == TabNetwork)
		foot += "     Square Shares";
	if (library().scanning())
		foot += "     (searching " + library().status() + ")";
	else if (!shown.empty())
		foot += "     " + focusedPath;
	hint(foot.c_str());
}

