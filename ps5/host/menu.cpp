/*
 * PSGopher - the game list and its settings (menu.h).
 *
 * The display: a Vulkan instance and device of the list's own on RADV, the display's plane surface
 * through ps5/sdl3 (VK_KHR_display, as Gopher64's), a FIFO swapchain, one render pass; all of it
 * ended before a game starts, so Gopher64's parallel-rdp makes its own as it does on the desktop.
 * Vulkan's entry points are volk's, the same table parallel-rdp loads again for itself.
 *
 * The pad: player 1's, read with the PS5 layer's pad_poll and given to Dear ImGui as its gamepad
 * (the D-pad and left stick move, Cross chooses); L1/R1 change the tab, OPTIONS opens the settings,
 * TRIANGLE searches again, SQUARE (Network) manages the shares, CIRCLE goes back.
 *
 * Settings: Gopher64's are its config.json, read and written through Gopher64's own Config
 * (psgopher_setting_get/set in vendor/gopher64/src/psgopher.rs), so they are the settings every game
 * runs with and they persist; PSGopher's own are psgopher.ini (title_settings.h). Network shares are
 * OGBox's (shares.h), mounted by ps5vfs at /smb/<name> and written to network.cfg as they change.
 *
 * SPDX-License-Identifier: GPL-3.0-or-later
 */
