void startShares(const std::string &titleDir)
{
	g_titleDir = titleDir;
	static std::string shadow;
	shadow = titleDir + "/sce_sys/param.json";
	ps5vfs_set_shadow_path(shadow.c_str());
	ps5vfs_set_log([](const char *line) { ::say("vfs: %s", line); });
	struct stat st;
	if (stat(kNetworkFile, &st) != 0) {
		ShareFile empty;
		writeShares(kNetworkFile, empty, nullptr);
	}
	ShareFile file;
	std::string error;
	if (!readShares(kNetworkFile, file, &error)) {
		::say("shares: %s: %s", kNetworkFile, error.c_str());
		return;
	}
	std::vector<std::string> taken;
	int mounted = 0;
	for (Share &s : file.shares) {
		if (mountShare(s, file, taken, &error)) {
			taken.push_back(s.mount);
			mounted++;
		} else
			::say("shares: %s: %s", s.name.c_str(), error.c_str());
	}
	::say("shares: %d of %zu mounted (%s)", mounted, file.shares.size(), kNetworkFile);
	g_shares = file;
}

MenuResult runMenu(const std::string &notice)
{
#ifndef PSGOPHER_MENU_HOST
	SDL_InitSubSystem(SDL_INIT_GAMEPAD); /* the pads, once, and this thread as SDL's main one */
#endif
	/* a game left in HDR10 would show the list's SDR pixels as HDR: off first (Crux2's rule: idle) */
	if (wsi_videoout_hdr10 && wsi_videoout_set_hdr10 && wsi_videoout_hdr10())
		wsi_videoout_set_hdr10(0);

	Menu menu;
	menu.title.load();
	if (g_displayAtStart.empty())
		g_displayAtStart = menu.title.display;
	menu.displayAtStart = g_displayAtStart;
	menu.elevationOff = access((g_titleDir + "/elevation-off.txt").c_str(), F_OK) == 0;
	menu.shares = g_shares; /* with where each is mounted */
	if (!notice.empty())
		menu.tell(notice, 10);

	Display d;
	if (!openDisplay(d)) {
		closeDisplay(d);
		return {};
	}
	IMGUI_CHECKVERSION();
	ImGui::CreateContext();
	ImGuiIO &io = ImGui::GetIO();
	io.IniFilename = nullptr;
	io.LogFilename = nullptr;
	io.ConfigFlags |= ImGuiConfigFlags_NavEnableGamepad;
	io.BackendFlags |= ImGuiBackendFlags_HasGamepad;
	io.ConfigNavCursorVisibleAlways = true;
	ImFontConfig fc;
	fc.FontDataOwnedByAtlas = false;
	/* the Live Board's faces: JetBrains Mono first (ImGui's own widgets: the shares' pages, the keyboard) */
	menu.fonts.mono = io.Fonts->AddFontFromMemoryTTF((void *)font_mono, (int)font_mono_size, 26.0f, &fc);
	menu.fonts.mono_bold = io.Fonts->AddFontFromMemoryTTF((void *)font_mono_bold, (int)font_mono_bold_size, 26.0f, &fc);
	menu.fonts.mono_heavy = io.Fonts->AddFontFromMemoryTTF((void *)font_mono_heavy, (int)font_mono_heavy_size, 26.0f, &fc);
	menu.fonts.display = io.Fonts->AddFontFromMemoryTTF((void *)font_bricolage, (int)font_bricolage_size, 26.0f, &fc);
	style(d.extent.height / 1080.0f);

	ImGui_ImplVulkan_InitInfo init{};
	init.ApiVersion = VK_API_VERSION_1_3;
	init.Instance = d.instance;
	init.PhysicalDevice = d.gpu;
	init.Device = d.device;
	init.QueueFamily = d.family;
	init.Queue = d.queue;
	/* the font atlas's pages, the board and the logo, every cover the cache keeps, and room to spare:
	 * 16 sets were too few for the covers (the console's SIGABRT in GetTexID, FE-001) */
	init.DescriptorPoolSize = IMGUI_IMPL_VULKAN_MINIMUM_SAMPLED_IMAGE_POOL_SIZE + 2 + (uint32_t)Menu::kCovers + 16;
	init.CheckVkResultFn = [](VkResult r) {
		if (r < 0)
			say("menu: ImGui's Vulkan backend: VkResult %d", (int)r);
	};
	init.MinImageCount = 2;
	init.ImageCount = std::max<uint32_t>(2, (uint32_t)d.images.size()); /* (the host test draws into one) */
	init.PipelineInfoMain.RenderPass = d.pass;
	init.PipelineInfoMain.Subpass = 0;
	init.PipelineInfoMain.MSAASamples = VK_SAMPLE_COUNT_1_BIT;
	if (!ImGui_ImplVulkan_Init(&init)) {
		say("menu: ImGui's Vulkan backend did not start");
		ImGui::DestroyContext();
		closeDisplay(d);
		return {};
	}
	d.imgui = true;

	/* the art: the title folder's art/ (PSGOPHER_ART for the host tests) */
	{
		const char *art = getenv("PSGOPHER_ART");
		const std::string dir = art ? std::string(art) : g_titleDir + "/art";
		menu.board_texture = uploadTexture(d, loadImage(dir + "/board.png"));
		menu.logo_texture = uploadTexture(d, loadImage(dir + "/logo.png"));
	}
	{
		FrontendHost host;
		Menu *m = &menu;
		host.get = [m](const char *key) { return m->get(key); };
		host.set = [m](const char *key, int64_t v) { m->set(key, v); };
		host.title = &menu.title;
		host.display_at_start = menu.displayAtStart;
		host.play = [m](const Game &g, int slot) {
			m->result.load_state = slot;
			m->play(g);
		};
		host.benchmark = [m](const Game &g, int slot) {
			m->result.load_state = slot;
			m->result.benchmark = true;
			m->play(g);
		};
		host.shares = [m] { m->go(Screen::Shares); };
		host.close = [m] {
			m->result.play = false;
			m->done = true;
		};
		host.tell = [m](const std::string &t) { m->tell(t); };
		host.elevated = [] { return psgopher_sandbox_elevated() != 0; };
		host.elevation_off = [m] { return m->elevationOff; };
		host.set_elevation_off = [m](bool off) {
			const std::string file = g_titleDir + "/elevation-off.txt";
			if (off) {
				if (FILE *w = fopen(file.c_str(), "w")) {
					fclose(w);
					m->elevationOff = true;
				}
			} else if (unlink(file.c_str()) == 0)
				m->elevationOff = false;
			m->tell(m->elevationOff ? "PSGopher stays in its sandbox from the next start (no USB drives)"
			                        : "PSGopher leaves its sandbox from the next start");
		};
		host.share_count = [m] { return (int)m->shares.shares.size(); };
		host.busy = [] { return g_copy.state == 1; };
		host.notice = [m] { return now_seconds() < m->noticeUntil ? m->notice : std::string(); };
		host.cheats_of = [](const std::string &game) {
			std::string text(256 * 1024, '\0');
			size_t n = psgopher_cheats_of(game.c_str(), text.data(), text.size());
			if (n >= text.size()) {
				text.assign(n + 1, '\0');
				n = psgopher_cheats_of(game.c_str(), text.data(), text.size());
			}
			text.resize(std::min(n, text.size() - 1));
			return text;
		};
		host.cheat_set = [](const std::string &game, const std::string &name, bool on, const std::string &option) {
			return psgopher_cheat_set(game.c_str(), name.c_str(), on, option.c_str());
		};
		Display *dp = &d;
		host.cover = [m, dp](const Game &g) -> std::pair<ImTextureID, float> {
			auto it = m->covers.find(g.name);
			if (it != m->covers.end()) {
				it->second.shown = m->frames;
				return { it->second.id, it->second.aspect };
			}
			/* one upload a frame (each waits for the queue) */
			if (m->uploaded_at == m->frames)
				return { ImTextureID_Invalid, 0.0f };
			/* the cache full: room is made by letting go of the least lately shown cover, if it was
			 * not shown in the last two frames; otherwise nothing is taken (it stays with the web
			 * thread for later) and the cache never grows past kCovers (FE-003) */
			auto oldest = m->covers.end();
			if (m->covers.size() >= Menu::kCovers) {
				oldest = m->covers.begin();
				for (auto c = m->covers.begin(); c != m->covers.end(); ++c)
					if (c->second.shown < oldest->second.shown)
						oldest = c;
				if (oldest->second.shown + 2 >= m->frames)
					return { ImTextureID_Invalid, 0.0f };
			}
			Image picture;
			if (webCover(g.name, &picture) != WebState::Ready)
				return { ImTextureID_Invalid, 0.0f };
			m->uploaded_at = m->frames;
			if (oldest != m->covers.end()) {
				if (oldest->second.id != ImTextureID_Invalid)
					freeTexture(*dp, oldest->second.id);
				webForget(oldest->first);
				m->covers.erase(oldest);
			}
			/* (a failed upload is kept as no texture, so it is not tried again each frame; it is let
			 * go like any other when room is needed, and asked for again after that) */
			Menu::Cover c;
			c.id = uploadTexture(*dp, picture);
			c.aspect = picture.height ? (float)picture.width / (float)picture.height : 0;
			c.shown = m->frames;
			m->covers[g.name] = c;
			return { c.id, c.aspect };
		};
		host.about = [](const Game &g) { return webAbout(g.name); };
		host.text = [m](const char *key) { return m->text(key); };
		host.set_text = [m](const char *key, const std::string &value) { return m->setText(key, value); };
		host.profiles = [m] { return m->profiles(); };
		host.profile_new = [m](const std::string &name) {
			const bool ok = psgopher_profile_new(name.c_str());
			m->profilesRead = false;
			if (ok)
				m->tell("Profile \"" + name + "\" made with Gopher64's default bindings");
			return ok;
		};
		host.profile_delete = [m](const std::string &name) {
			const bool ok = psgopher_profile_delete(name.c_str());
			m->profilesRead = false;
			m->texts.clear(); /* (ports that had it have "default" now) */
			if (ok)
				m->tell("Profile \"" + name + "\" taken away");
			return ok;
		};
		host.binding = [m](const std::string &profile, int index) { return m->binding(profile, index); };
		host.bind = [m](const std::string &profile, int index, const Binding &b) {
			const bool ok = psgopher_profile_bind(profile.c_str(), index, b.kind, b.id, b.axis);
			m->bindings.erase(std::make_pair(profile, index));
			return ok;
		};
		host.profile_number = [m](const std::string &profile, int what, int64_t value, bool set) {
			const auto key = std::make_pair(profile, what);
			if (!set) {
				auto it = m->profileNumbers.find(key);
				if (it != m->profileNumbers.end())
					return it->second;
			}
			return m->profileNumbers[key] = psgopher_profile_number(profile.c_str(), what, value, set);
		};
		menu.front = std::make_unique<Frontend>(std::move(host));
	}

	/* input starts once every button is up (a game was left with OPTIONS and the touch pad) */
	bool released = false;
	Buttons b;
	struct pad p = {};
	double last = now_seconds();
	while (!menu.done) {
		pad_poll(&p);
		if (!released)
			released = p.held == 0;
		b.held = released ? p.held : 0;
		b.pressed = released ? p.pressed : 0;
		{
			/* the front end's pad: L2 and R2 as buttons past half way, and when each went down */
			const uint32_t was = menu.input.held;
			uint32_t held = b.held;
			if (released && p.l2 > .5f)
				held |= PAD_L2_DIGITAL;
			if (released && p.r2 > .5f)
				held |= PAD_R2_DIGITAL;
			menu.frames++;
			menu.input.now = (float)now_seconds();
			menu.input.held = held;
			menu.input.pressed = held & ~was;
			menu.input.left_x = released ? p.left_x : 0, menu.input.left_y = released ? p.left_y : 0;
			menu.input.right_x = released ? p.right_x : 0, menu.input.right_y = released ? p.right_y : 0;
			menu.input.l2 = released ? p.l2 : 0, menu.input.r2 = released ? p.r2 : 0;
			for (int bit = 0; bit < 32; bit++)
				if (menu.input.pressed & (1u << bit))
					menu.input.held_since[bit] = menu.input.last_repeat[bit] = menu.input.now;
		}
		struct pad quiet = {};
		feedImGui(released ? p : quiet); /* (the list's window takes no navigation while the keyboard is up) */
		const double now = now_seconds();
		io.DeltaTime = (float)std::max(1e-3, now - last);
		last = now;
		frame(d, menu, b);
	}
	/* the covers' textures go with the display: each is asked for again in the next menu (from the
	 * cache folder), else they never came back after a game (FE-002) */
	for (const auto &c : menu.covers)
		webForget(c.first);
	menu.covers.clear();
	closeDisplay(d);
	ImGui::DestroyContext();
	if (menu.result.play)
		say("menu: playing %s", menu.result.rom.c_str());
	return menu.result;
}

